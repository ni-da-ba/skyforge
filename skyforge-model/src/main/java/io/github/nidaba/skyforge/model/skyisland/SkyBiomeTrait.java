package io.github.nidaba.skyforge.model.skyisland;

/**
 * Stable environmental descriptors for authored sky habitats.
 *
 * <p>These traits describe static regional habitat character. They do not represent live
 * atmospheric samples or species/spawn policy.
 */
public enum SkyBiomeTrait {
    /** Broad, unobstructed aerial space. */
    OPEN_AIR,

    /** Persistent association with a cloud layer or cloud formations. */
    CLOUD_ASSOCIATED,

    /** Shelter formed by the mass and lee geometry of nearby islands. */
    TERRAIN_SHELTERED
}
